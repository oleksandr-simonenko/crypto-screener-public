#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""secrets_guard.py — вычистить ключи из любого текста ПЕРЕД печатью.

ЗАЧЕМ ЭТО ПОЯВИЛОСЬ (01.09.2026, находка ревизии пакета СКРИНЕР-ПОЛНЫЙ)

Во всех скриптах репозитория Telegram зовётся так:

    S.post(f"https://api.telegram.org/bot{TG_TOKEN}/sendMessage", ...)

Токен сидит В САМОМ URL. А `requests` при сетевом сбое кладёт полный URL в
текст исключения — и строка

    except Exception as e:
        print(f"Telegram недоступен: {e}")

печатает в stdout ВЕСЬ токен бота. Достаточно одного таймаута, чтобы ключ
оказался в логе прогона GitHub Actions. То же самое с Anthropic: заголовок
`x-api-key` попадает в текст некоторых исключений `requests`.

ПОЧЕМУ «Actions и так маскирует секреты» — НЕ ОТВЕТ.
Маскирование — сеть безопасности, а не гарантия: оно работает по точному
совпадению строки, не срабатывает на изменённом виде значения (перенос
строки, urlencode, обрезка) и вовсе отсутствует при локальном прогоне у
пилота. Ключ, напечатанный в консоль, переживает консоль: лог прогона
хранится, транскрипт сессии сохраняется на диск. Единственная честная
реакция на напечатанный ключ — перевыпуск ключа, поэтому дешевле не печатать.

ЧТО ДЕЛАЕТ ЭТОТ МОДУЛЬ
`redact(text)` вырезает из строки (а) точные значения известных переменных
окружения с ключами и (б) характерные ФОРМЫ ключей, даже если переменной в
этом процессе нет вовсе. Второе важно: чужой ключ из чужого окружения тоже
не должен утечь.

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ
Он не прячет факт ошибки: сообщение об ошибке остаётся, вырезается только
секрет. Тихо проглатывать сбой хуже, чем печатать его без ключа.

ЧЕСТНАЯ ГРАНИЦА: модуль вычищает то, что похоже на ключ, — он не может
поймать секрет неизвестной формы, значение которого не лежит в окружении.
Настоящая защита — не совать ключ в URL; здесь она недостижима, потому что
так устроен Telegram Bot API. Поэтому это второй слой, а не первый.

ПРАВИЛО ВЫЗОВА: redact ДО среза. `redact(r.text)[:300]`, а НЕ
`redact(r.text[:300])` — срез может разрезать токен пополам, и обрубок,
слишком короткий для шаблонов, ушёл бы в печать (С-19, 02.09.2026).

Зависимости: только stdlib.
"""

import os
import re

# Переменные окружения, значения которых нельзя печатать никогда.
# С-19 (02.09.2026): добавлены GH_TOKEN (gh CLI читает его, а не GITHUB_TOKEN)
# и прокси-переменные — в URL прокси часто сидят логин:пароль, и
# requests.exceptions.ProxyError цитирует этот URL целиком. Нижний регистр
# прокси-имён — потому что на Linux каноничен именно он, а os.getenv там
# регистрозависим.
SECRET_ENV_VARS = (
    "TELEGRAM_BOT_TOKEN",
    "ANTHROPIC_API_KEY",
    "COINGECKO_API_KEY",
    "GITHUB_TOKEN",
    "GH_TOKEN",
    "HTTP_PROXY",
    "HTTPS_PROXY",
    "ALL_PROXY",
    "http_proxy",
    "https_proxy",
    "all_proxy",
)

PLACEHOLDER = "<КЛЮЧ ВЫРЕЗАН>"

# Формы ключей, узнаваемые сами по себе. Порядок важен: длинные шаблоны
# идут раньше, чтобы короткий не съел кусок длинного.
# С-19 (02.09.2026), что изменилось в телеграм-шаблонах:
#   * id до 20 цифр вместо 12 — Telegram уже раздаёт id длиннее, а токен
#     с 13-значным id прежние шаблоны пропускали ЦЕЛИКОМ;
#   * двоеточие может приехать URL-кодированным — %3A/%3a;
#   * хвост может быть разорван переносом строки (лог заворачивает длинные
#     строки) — \r\n включены в класс символов хвоста. Цена: если следующая
#     строка лога состоит из одних букв-цифр, чистка съест и её начало.
#     Осознанно: пересечь лишнего дешевле, чем напечатать половину ключа.
_PATTERNS = (
    # Telegram: .../bot<цифры>:<буквы-цифры-_-> — вырезаем ТОЛЬКО токен,
    # оставляя «/bot<ВЫРЕЗАН>/sendMessage», чтобы по сообщению было видно,
    # какой именно вызов упал.
    (re.compile(r"(?<=/bot)\d{6,20}(?::|%3[Aa])[A-Za-z0-9_\-\r\n]{19,}[A-Za-z0-9_-]"),
     PLACEHOLDER),
    # Тот же токен, встреченный вне URL. Отдельный шаблон, а не один на оба
    # случая: перед «/bot…» стоит буква t, и \b там не срабатывает — у
    # in-URL случая работает ТОЛЬКО lookbehind-шаблон выше.
    (re.compile(r"\b\d{6,20}(?::|%3[Aa])[A-Za-z0-9_\-\r\n]{29,}[A-Za-z0-9_-]"),
     PLACEHOLDER),
    # Anthropic.
    (re.compile(r"\bsk-ant-[A-Za-z0-9_-]{10,}"), PLACEHOLDER),
    # CoinGecko demo/pro.
    (re.compile(r"\bCG-[A-Za-z0-9]{10,}\b"), PLACEHOLDER),
    # GitHub.
    (re.compile(r"\bgh[pousr]_[A-Za-z0-9]{20,}\b"), PLACEHOLDER),
    # Креды в любом URL: scheme://логин:пароль@хост — так выглядит прокси с
    # паролем в тексте ProxyError, даже когда самой переменной в окружении
    # процесса уже нет. Хост остаётся видимым — по нему ищут причину сбоя.
    (re.compile(r"(?<=://)[^/\s@:]{1,64}:[^/\s@]{1,128}(?=@)"), PLACEHOLDER),
)

# Ниже этой длины значение переменной окружения не вырезаем: пустая строка
# или «0» встретились бы в каждом тексте и превратили бы вывод в кашу.
_MIN_SECRET_LEN = 8


def redact(text):
    """Вернуть текст без секретов. На вход годится что угодно, включая
    исключение: оно приводится к строке.

    Никогда не падает: задача этой функции — сделать печать безопасной,
    и исключение внутри неё обессмыслило бы её саму.
    """
    try:
        s = text if isinstance(text, str) else str(text)
    except Exception:
        return "<текст не приводится к строке>"

    try:
        # (а) точные значения из окружения — самый надёжный проход.
        for name in SECRET_ENV_VARS:
            val = (os.getenv(name) or "").strip()
            if len(val) >= _MIN_SECRET_LEN and val in s:
                s = s.replace(val, PLACEHOLDER)
        # (б) узнаваемые формы — работают и без окружения.
        for rx, repl in _PATTERNS:
            s = rx.sub(repl, s)
    except Exception:
        # Если что-то пошло не так в самой чистке — отдаём заглушку, а не
        # исходный текст: лучше потерять сообщение об ошибке, чем ключ.
        return "<текст скрыт: сбой очистки секретов>"
    return s


def safe_print(*parts):
    """print(), пропущенный через redact(). Для мест, где в текст может
    попасть исключение сетевой библиотеки."""
    print(" ".join(redact(p) for p in parts))


def main():
    """Самопроверка руками: python secrets_guard.py

    Настоящие ключи НЕ используются и не читаются — только выдуманные
    образцы нужной формы.
    """
    samples = [
        "Telegram недоступен: HTTPSConnectionPool(host='api.telegram.org', port=443): "
        "Max retries exceeded with url: /bot123456789:AAFakeFakeFakeFakeFakeFakeFake12345/sendMessage",
        "ключ sk-ant-api03-ZZZZZZZZZZZZZZZZZZZZ протёк в текст",
        "заголовок x-cg-demo-api-key: CG-abcdefghij123456",
        "обычная строка без секретов",
    ]
    for s in samples:
        print("ДО:    %s" % s)
        print("ПОСЛЕ: %s" % redact(s))
        print("-" * 60)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
